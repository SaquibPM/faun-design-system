/** Writes src/scales/scales.json. Committed so every value is reviewable; CI checks it is current. */
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { SCALES, alphaOver, hex, p3, stepColour, type Appearance } from "./scales.ts";

const APPEARANCES: Appearance[] = ["light", "dark", "light-hc", "dark-hc"];
const out: any = {
  $description: "Generated by scripts/generate-scales.ts. Steps 1–12 solid, a1–a12 alpha twins over step 1, p3 = Display P3.",
  scales: {},
};

for (const [name, def] of Object.entries(SCALES)) {
  const s: any = { description: def.description, onSolid: def.onSolid };
  for (const ap of APPEARANCES) {
    const steps: Record<string, string> = {};
    const p3s: Record<string, string> = {};
    const solid = Array.from({ length: 12 }, (_, i) => stepColour(def, ap, i + 1));
    solid.forEach((c, i) => {
      steps[String(i + 1)] = hex(c);
      p3s[String(i + 1)] = p3(c);
    });
    // Alpha twins composite over the app background: white in light themes, gray-1 in dark themes.
    const bg = ap.startsWith("light") ? "#ffffff" : hex(stepColour(SCALES.gray!, ap, 1));
    solid.forEach((_, i) => {
      steps[`a${i + 1}`] = alphaOver(steps[String(i + 1)]!, bg);
    });
    s[ap] = { steps, p3: p3s };
  }
  out.scales[name] = s;
}

writeFileSync(resolve(import.meta.dirname, "../src/scales/scales.json"), JSON.stringify(out, null, 2) + "\n");
for (const [name, s] of Object.entries<any>(out.scales)) {
  console.log(name.padEnd(10), "L", Object.entries(s.light.steps).filter(([k]) => !k.startsWith("a")).map(([, v]) => v).join(" "));
  console.log("".padEnd(10), "D", Object.entries(s.dark.steps).filter(([k]) => !k.startsWith("a")).map(([, v]) => v).join(" "));
}
