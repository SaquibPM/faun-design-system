/**
 * Generates src/generated/*.ts from the curated Lucide list and Faun's own glyphs (src/custom/*.svg).
 * Output is committed-free (dist only) but deterministic.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { basename, resolve } from "node:path";
import { CURATED } from "./curated.ts";

const ROOT = resolve(import.meta.dirname, "..");
const require = createRequire(import.meta.url);
const lucideNodes: Record<string, [string, Record<string, string>][]> = require("lucide-static/icon-nodes.json");
const lucideTags: Record<string, string[]> = require("lucide-static/tags.json");
const lucideVersion: string = require("lucide-static/package.json").version;

const pascal = (s: string) => s.replace(/(^|-)([a-z0-9])/g, (_, __, c: string) => c.toUpperCase());

type Entry = { name: string; component: string; category: string; source: string; keywords: string[]; node: [string, Record<string, string>][] };
const entries: Entry[] = [];

for (const [category, icons] of Object.entries(CURATED)) {
  for (const [name, lucide] of Object.entries(icons)) {
    const node = lucideNodes[lucide];
    if (!node) throw new Error(`Lucide icon "${lucide}" not found (for ${name})`);
    entries.push({ name, component: `Icon${pascal(name)}`, category, source: `lucide:${lucide}@${lucideVersion}`, keywords: lucideTags[lucide] ?? [], node: node.map(([t, a]) => [t, stripKey(a)]) });
  }
}

/** Parses the simple SVG subset Faun glyphs use: path, circle, rect, line, polyline. */
function parseSvg(svg: string): [string, Record<string, string>][] {
  const body = svg.replace(/<svg[^>]*>/, "").replace(/<\/svg>/, "");
  const out: [string, Record<string, string>][] = [];
  for (const m of body.matchAll(/<(path|circle|rect|line|polyline|ellipse)\s([^>]*?)\/>/g)) {
    const attrs: Record<string, string> = {};
    for (const a of m[2]!.matchAll(/([a-zA-Z-]+)="([^"]*)"/g)) attrs[a[1]!.replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())] = a[2]!;
    out.push([m[1]!, attrs]);
  }
  if (!out.length) throw new Error("empty glyph");
  return out;
}
function stripKey(a: Record<string, string>) {
  const { key: _k, ...rest } = a;
  return rest;
}

const CUSTOM_META: Record<string, string[]> = {
  "scope-1": ["ghg", "direct emissions", "combustion", "facility"],
  "scope-2": ["ghg", "purchased electricity", "energy", "indirect"],
  "scope-3": ["ghg", "value chain", "suppliers", "upstream", "downstream"],
  orchestrator: ["agent", "orchestrator", "workflow", "task graph"],
  "sub-agent": ["sub-agent", "agent", "task node"],
  "approval-gate": ["human in the loop", "approval", "review", "sign-off"],
  provenance: ["lineage", "source", "audit trail", "evidence"],
  "emission-factor": ["factor", "coefficient", "co2e", "multiplier"],
  ledger: ["emissions ledger", "book", "records"],
  disclosure: ["report", "esrs", "datapoint", "filing"],
  materiality: ["double materiality", "matrix", "impact", "financial"],
};
const customDir = resolve(ROOT, "src/custom");
for (const file of readdirSync(customDir).filter((f) => f.endsWith(".svg")).sort()) {
  const name = basename(file, ".svg");
  entries.push({ name, component: `Icon${pascal(name)}`, category: "esg", source: "faun", keywords: CUSTOM_META[name] ?? [], node: parseSvg(readFileSync(resolve(customDir, file), "utf8")) });
}

const names = entries.map((e) => e.name);
const dup = names.filter((n, i) => names.indexOf(n) !== i);
if (dup.length) throw new Error(`Duplicate icon names: ${dup.join(", ")}`);

mkdirSync(resolve(ROOT, "src/generated"), { recursive: true });
writeFileSync(
  resolve(ROOT, "src/generated/icons.ts"),
  `/* Generated by scripts/generate.ts — do not edit. */\nimport { createIcon } from "../create-icon.js";\n\n` +
    entries.map((e) => `/** ${e.category} · ${e.source}${e.keywords.length ? ` · ${e.keywords.slice(0, 6).join(", ")}` : ""} */\nexport const ${e.component} = /*#__PURE__*/ createIcon(${JSON.stringify(e.name)}, ${JSON.stringify(e.node)});`).join("\n") +
    "\n",
);
writeFileSync(
  resolve(ROOT, "src/generated/registry.ts"),
  `/* Generated by scripts/generate.ts — do not edit. Importing this pulls in every icon; prefer named imports. */\nimport * as I from "./icons.js";\n\nexport const icons = {\n${entries.map((e) => `  ${JSON.stringify(e.name)}: I.${e.component},`).join("\n")}\n} as const;\n\nexport type IconName = keyof typeof icons;\n`,
);
writeFileSync(
  resolve(ROOT, "src/generated/manifest.json"),
  JSON.stringify({ lucideVersion, count: entries.length, icons: entries.map(({ node: _n, ...rest }) => rest) }, null, 2) + "\n",
);
console.log(`icons: ${entries.length} (${entries.filter((e) => e.source === "faun").length} Faun glyphs)`);
